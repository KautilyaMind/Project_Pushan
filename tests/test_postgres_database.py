"""Unit coverage for the PostgreSQL/Neon database compatibility layer."""

import unittest
from unittest.mock import patch

from app.database.db import execute, initialize_database, is_postgres


class _Cursor:
    def fetchone(self):
        return {"id": 1}


class _PostgresConnection:
    __module__ = "psycopg"

    def __init__(self):
        self.statements = []
        self.closed = False

    def __enter__(self):
        return self

    def __exit__(self, *_args):
        return False

    def execute(self, sql, parameters=()):
        self.statements.append((sql, tuple(parameters)))
        return _Cursor()

    def close(self):
        self.closed = True


class PostgresDatabaseTests(unittest.TestCase):
    def test_neon_url_is_recognized(self):
        self.assertTrue(is_postgres("postgresql://user:secret@example/db"))
        self.assertFalse(is_postgres("data/pushan.db"))

    def test_parameters_are_converted_for_psycopg(self):
        connection = _PostgresConnection()
        execute(connection, "SELECT * FROM fields WHERE field_id = ?", ("FIELD_1",))
        self.assertEqual(
            connection.statements[0],
            ("SELECT * FROM fields WHERE field_id = %s", ("FIELD_1",)),
        )

    def test_postgres_schema_uses_identity_columns(self):
        connection = _PostgresConnection()
        with patch("app.database.db.get_connection", return_value=connection):
            initialize_database("postgresql://user:secret@example/db")
        ddl = "\n".join(statement for statement, _ in connection.statements)
        self.assertIn("GENERATED BY DEFAULT AS IDENTITY", ddl)
        self.assertNotIn("AUTOINCREMENT", ddl)
        self.assertIn("ON CONFLICT (version) DO NOTHING", ddl)
        self.assertTrue(connection.closed)


if __name__ == "__main__":
    unittest.main()
